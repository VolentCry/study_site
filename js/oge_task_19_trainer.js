  // Генератор заданий: выбор пресета либо динамическая сборка 3 утверждений
  function generateTask(category = 'all') {
    let pool = TASK_PRESETS;
    if (category && category !== 'all' && category !== 'mixed_all') {
      pool = TASK_PRESETS.filter(t => t.category === category);
      if (pool.length === 0) pool = TASK_PRESETS;
    }

    const preset = pickRandom(pool);

    // Случайным образом перемешиваем порядок утверждений в карточке,
    // чтобы ученик не запоминал позиции, но гарантируем, что правильный ответ пересчитан.
    const shuffledStatements = shuffle(preset.statements);
    
    // Гарантия выполнения требования: обязательно хотя бы 1 верное утверждение!
    const trueItems = shuffledStatements.filter(s => s.isTrue);
    if (trueItems.length === 0) {
      // Подстраховка (в нашей базе во всех заданиях 1-3 верных утверждения)
      shuffledStatements[0].isTrue = true;
    }

    const correctIndices = [];
    shuffledStatements.forEach((st, idx) => {
      if (st.isTrue) {
        correctIndices.push(idx + 1);
      }
    });

    const expectedAnswer = correctIndices.join('');

    const questionHtml = `
      <div class="oge19-statements-list" role="list">
        ${shuffledStatements.map((st, idx) => `
          <div class="oge19-statement-item" role="listitem">
            <span class="oge19-num-badge">${idx + 1}</span>
            <span class="oge19-statement-text">${st.text}</span>
          </div>
        `).join('')}
      </div>
    `;

    const solutionSteps = [
      `<strong>Разбор каждого утверждения:</strong>`,
      ...shuffledStatements.map((st, idx) => {
        const icon = st.isTrue ? '✅' : '❌';
        const verdict = st.isTrue ? '<strong>ВЕРНО</strong>' : '<strong>НЕВЕРНО</strong>';
        return `${icon} <strong>${idx + 1})</strong> ${st.text}<br><span class="oge19-verdict-line">Статус: ${verdict}.</span> <em>Обоснование:</em> ${st.reason}`;
      }),
      `<strong>Итоговый ответ:</strong> верными являются утверждения под номерами <strong>${correctIndices.join(' и ')}</strong>. В бланк ответов ОГЭ число записывается без пробелов, запятых и других знаков: <strong>${expectedAnswer}</strong>.`
    ];

    return {
      id: 'oge19_' + preset.id + '_' + Date.now(),
      presetId: preset.id,
      category: preset.category,
      catName: preset.catName,
      promptText: 'Какое из следующих утверждений верно? Возможно более одного ответа.',
      questionHtml,
      statements: shuffledStatements,
      correctIndices,
      expectedAnswer,
      displayAnswer: correctIndices.join(' или ' + correctIndices.slice().reverse().join('')) === expectedAnswer ? expectedAnswer : `${expectedAnswer} (в любом порядке цифр)`,
      solutionSteps
    };
  }

  // Проверка ответа: допускаются цифры в порядке возрастания или любом порядке
  function checkAnswer(userValue, task) {
    if (!userValue || typeof userValue !== 'string') {
      return { isCorrect: false, message: 'Пожалуйста, введите номера верных утверждений.' };
    }

    const clean = userValue.replace(/[^0-9]/g, '');
    if (!clean) {
      return { isCorrect: false, message: 'Ответ должен содержать цифры номеров (например: 1, 13 или 123).' };
    }

    const userDigits = clean.split('').map(Number).sort((a, b) => a - b);
    const expectedDigits = task.correctIndices.slice().sort((a, b) => a - b);

    // Удаляем дубликаты цифр, если ученик ввёл например 11
    const uniqueUser = Array.from(new Set(userDigits));

    const isMatch = uniqueUser.length === expectedDigits.length &&
      uniqueUser.every((val, idx) => val === expectedDigits[idx]);

    if (isMatch) {
      return {
        isCorrect: true,
        message: '🎉 Абсолютно верно! Все геометрические утверждения определены правильно (+25 XP).'
      };
    } else {
      return {
        isCorrect: false,
        message: `✕ Не совсем так. Верный ответ: ${task.expectedAnswer}. Посмотрите обоснование каждого утверждения по кнопке решения.`
      };
    }
  }

  return {
    generateTask,
    checkAnswer,
    TASK_PRESETS
  };
