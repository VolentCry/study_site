function getPhysicsSkill(topic) {
const normalizedTopic = topic.toLocaleLowerCase('ru-RU');
if (/атомн|ядерн|квант|фотоэффект|радиоактив/.test(normalizedTopic)) return 'modernPhysics';
if (/тепл|внутренн|плавлен|испар|агрегат/.test(normalizedTopic)) return 'thermal';
if (/магнит|индукц/.test(normalizedTopic)) return 'magnetism';
if (/электр|электростат|конденсатор|сила тока/.test(normalizedTopic)) return 'electricity';
if (/колеб|волн|звук/.test(normalizedTopic)) return 'waves';
if (/оптик|свет|линз/.test(normalizedTopic)) return 'optics';
if (/величин|измерен/.test(normalizedTopic)) return 'measurement';
if (/механ|кинемат|динамик|движен|ньютон|сил|давлен|рычаг|импульс|гравитац|тяготен|сохранен|трени|гука|архимед/.test(normalizedTopic)) return 'mechanics';
return 'generalPhysics';
}

